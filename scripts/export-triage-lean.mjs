/** Export the live triageMachine rule table as Lean data in ../boom. */
import { build } from "esbuild";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "../boom/src/archive/triage/TriageRules.lean");
const kinds = new Map([
  ["Leaf", "leaf"], ["Stem", "stem"], ["Fork", "fork"], ["App", "app"],
  ["Eval", "eval"], ["Call", "call"], ["Case", "case_"],
  ["Triage", "triage"], ["Dup", "dup"], ["Erase", "erase"],
]);

function kind(name) {
  const result = kinds.get(name);
  if (!result) throw new Error(`unknown triage agent ${name}`);
  return `.${result}`;
}

function end(value) {
  if (value.kind === "agent") return `End.agent ${value.index} ${value.slot}`;
  if (value.kind === "iface") return `End.iface ${value.side} ${value.slot}`;
  throw new Error(`unknown rule end ${JSON.stringify(value)}`);
}

function render(system) {
  const arities = system.types.map((type) => `(${kind(type.id)}, ${type.arity})`).join(", ");
  const rules = system.rules;
  const rows = rules.map((rule) => {
    const agents = rule.agents.map(kind).join(", ");
    const wires = rule.wires.map(([a, b]) => `(${end(a)}, ${end(b)})`).join(",\n      ");
    return `  { left := ${kind(rule.left)}, right := ${kind(rule.right)},\n    agents := [${agents}],\n    wires := [${wires}] }`;
  });
  return `-- Generated by netties/scripts/export-triage-lean.mjs. Do not edit by hand.
import TriageRuleModel

namespace TriageRules
open TriageRuleModel

def declaredArities : List (Kind × Nat) := [${arities}]

theorem agent_arities_match :
    declaredArities.all (fun pair => decide (pair.1.arity = pair.2)) = true :=
  by decide

theorem all_agent_kinds_present :
    declaredArities.map Prod.fst =
      [.leaf, .stem, .fork, .app, .eval, .call, .case_, .triage, .dup, .erase] :=
  by decide

def rules : List Rule := [
${rows.join(",\n")}
]

theorem rules_nodup : rules.Nodup := by decide

theorem rules_wellFormed :
    rules.all Rule.wellFormed = true := by decide

theorem each_rule_wellFormed {rule : Rule} (h : rule ∈ rules) :
    rule.used.Nodup ∧
      (∀ end_ ∈ rule.used, end_ ∈ rule.expected) ∧
      (∀ end_ ∈ rule.expected, end_ ∈ rule.used) := by
  have hall : ∀ r ∈ rules, r.wellFormed = true := by
    simpa only [List.all_eq_true] using rules_wellFormed
  exact (Rule.wellFormed_iff rule).mp (hall rule h)

theorem rules_nonOverlapping :
    rules.all (fun first =>
      rules.all (fun second => Rule.nonOverlapping first second)) = true :=
  by decide

theorem triage_branches_only_on_heads :
    rules.all Rule.branchesOnlyOnHeads = true := by decide

def rightsFor (kind : Kind) : List Kind :=
  (rules.filter fun rule => decide (rule.left = kind)).map Rule.right

theorem triage_has_all_three_head_rules :
    rightsFor .triage = [.leaf, .stem, .fork] := by decide

theorem case_has_all_three_head_rules :
    rightsFor .case_ = [.leaf, .stem, .fork] := by decide

theorem duplication_copies_each_constructor :
    rightsFor .dup = [.leaf, .stem, .fork, .app] ∧
    rules.all Rule.copyLayout = true := by decide

theorem erasure_recurses_over_each_constructor :
    rightsFor .erase = [.leaf, .stem, .fork, .app] ∧
    rules.all Rule.eraseLayout = true := by decide

theorem new_observers_are_eval_gated :
    rules.all Rule.observerBarrier = true ∧
    rules.all Rule.observerProvenance = true := by decide

end TriageRules
`;
}

const temporary = await mkdtemp(join(tmpdir(), "netties-triage-lean-"));
try {
  const bundle = join(temporary, "triage-machine.mjs");
  await build({
    entryPoints: [resolve(root, "src/core/triageMachine.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    outfile: bundle,
    logLevel: "silent",
  });
  const { triageMachine } = await import(pathToFileURL(bundle).href);
  const output = render(triageMachine().toJSON());
  if (process.argv.includes("--write")) {
    await writeFile(target, output);
    process.stdout.write(`Wrote ${target}\n`);
  } else if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8") !== output)
      throw new Error(`${target} is stale; run this script with --write`);
    process.stdout.write("Lean rule table matches triageMachine.ts\n");
  } else {
    throw new Error("pass --write or --check");
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
